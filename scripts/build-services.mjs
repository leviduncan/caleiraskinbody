// Runs after fetch-services. Combines src/data/services.json (from Cal.com) with
// services.config.json (what Cal.com cannot supply) into the list the page renders:
//   src/data/services.merged.json   the final menu
//   src/data/service-images.ts      static imports for the category photos named in the config
// Warnings are printed, never hidden. A broken config or a compliance guard hit stops the build.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { mergeServices } from "./lib/services-core.mjs";

const CACHE_FILE = "src/data/services.json";
const CONFIG_FILE = "services.config.json";
const MERGED_FILE = "src/data/services.merged.json";
const IMAGES_FILE = "src/data/service-images.ts";

function readJson(file) {
  if (!existsSync(file)) throw new Error(`${file} not found.`);
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`${file} is not valid JSON: ${error.message}`);
  }
}

const config = readJson(CONFIG_FILE);
const cache = existsSync(CACHE_FILE)
  ? readJson(CACHE_FILE)
  : { username: "", services: [] };
if (!existsSync(CACHE_FILE)) {
  console.warn(`[build-services] ${CACHE_FILE} is missing; the menu will show only coming-soon entries.`);
}

const { menu, warnings } = mergeServices(cache, config);
for (const warning of warnings) console.warn(`[build-services] ${warning}`);

// Static image imports, so Next still sizes and optimizes the photos like any other asset.
const imagePaths = [];
for (const service of menu.categories.flatMap((category) => category.services)) {
  const imagePath = service.image?.path;
  if (!imagePath) continue;
  if (!imagePath.startsWith("src/")) throw new Error(`Image "${imagePath}" must live under src/ (for example src/assets/photo.jpg).`);
  if (!existsSync(imagePath)) throw new Error(`Image "${imagePath}" for "${service.slug}" does not exist.`);
  if (!service.image.alt) throw new Error(`Service "${service.slug}" has an image but no alt text.`);
  if (!imagePaths.includes(imagePath)) imagePaths.push(imagePath);
}

const imports = imagePaths.map((p, i) => `import image${i} from "@/${p.slice(4)}";`);
const entries = imagePaths.map((p, i) => `  ${JSON.stringify(p)}: image${i},`);
const imagesSource = [
  "// Generated by scripts/build-services.mjs from services.config.json. Do not edit.",
  'import type { StaticImageData } from "next/image";',
  ...imports,
  "",
  "export const serviceImages: Record<string, StaticImageData> = {",
  ...entries,
  "};",
  "",
].join("\n");

writeFileSync(MERGED_FILE, `${JSON.stringify(menu, null, 2)}\n`);
writeFileSync(IMAGES_FILE, imagesSource);

const shown = menu.categories.reduce((sum, c) => sum + c.services.length, 0);
console.info(`[build-services] ${menu.categories.length} categories, ${shown} services.`);
